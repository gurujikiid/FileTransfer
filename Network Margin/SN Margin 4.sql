--1) Update Existing Record in Main Network Table
UPDATE SIEBELEXT.CX_NETWORK_MARGIN A
SET (A.MRP, A.DLP, A.DEALER_MARGIN, A.BASE_MARGIN, A.MYSCORE_MARGIN, A.STOCK_MARGIN, A.PDI_CHARGES, A.TOTAL_MARGIN, A.UPDATED,HANDLING_CHARGES)
= (SELECT B.MRP, B.DLP, B.DEALER_MARGIN, B.BASE_MARGIN, B.MYSCORE_MARGIN, B.STOCK_MARGIN, B.PDI_CHARGES, B.TOTAL_MARGIN, SYSDATE-0.22917 ,HANDLING_CHARGES
FROM ECUB90176909.CX_NET_MAR_24MAY14 B WHERE A.ROW_ID = B.ROW_ID)
WHERE EXISTS (SELECT * FROM ECUB90176909.CX_NET_MAR_24MAY14 B WHERE A.ROW_ID = B.ROW_ID 
AND B.DLR_CODE = '10231'
and B.ntw_code = '65502'
--one by one for each dealer in temp table ECUB003.CX_NETWORK_MARGIN
);
--2) Insert new records in Main Network Table
INSERT INTO SIEBELEXT.CX_NETWORK_MARGIN (VARIANT,ROW_ID,TRANSPORT_ZONE,DLR_CODE,NTW_CODE,PRICE_LIST,MRP,DLP,DEALER_MARGIN,BASE_MARGIN,MYSCORE_MARGIN,STOCK_MARGIN,PDI_CHARGES,TOTAL_MARGIN,CREATED,UPDATED,HANDLING_CHARGES)
SELECT VARIANT,ROW_ID,TRANSPORT_ZONE,DLR_CODE,NTW_CODE,PRICE_LIST,MRP,DLP,DEALER_MARGIN,BASE_MARGIN,MYSCORE_MARGIN,STOCK_MARGIN,PDI_CHARGES,TOTAL_MARGIN,SYSDATE-0.22917,SYSDATE-0.22917,HANDLING_CHARGES
FROM ECUB90176909.CX_NET_MAR_24MAY14 Y1
WHERE NOT EXISTS (SELECT 1 FROM SIEBELEXT.CX_NETWORK_MARGIN Y2 WHERE Y1.ROW_ID = Y2.ROW_ID
);


--3) Merge Statement only work if there are no duplicate at source and destination level
MERGE INTO SIEBELEXT.CX_NETWORK_MARGIN A USING ECUB90176909.CX_NET_MAR_24MAY14 B ON ( A.ROW_ID = B.ROW_ID )
WHEN MATCHED THEN UPDATE SET A.MRP =B.MRP, A.DLP=B.DLP, A.DEALER_MARGIN=B.DEALER_MARGIN, A.BASE_MARGIN=B.BASE_MARGIN, A.MYSCORE_MARGIN=B.MYSCORE_MARGIN, A.STOCK_MARGIN=B.STOCK_MARGIN, A.PDI_CHARGES=B.PDI_CHARGES, A.TOTAL_MARGIN=B.TOTAL_MARGIN, A.UPDATED=SYSDATE-0.22917,HANDLING_CHARGES=B.HANDLING_CHARGES                   
WHEN NOT MATCHED THEN INSERT (A.VARIANT,A.ROW_ID,A.TRANSPORT_ZONE,A.DLR_CODE,A.NTW_CODE,A.PRICE_LIST,A.MRP,A.DLP,A.DEALER_MARGIN,A.BASE_MARGIN,A.MYSCORE_MARGIN,A.STOCK_MARGIN,A.PDI_CHARGES,A.TOTAL_MARGIN,A.CREATED,A.UPDATED,A.HANDLING_CHARGES)  VALUES (B.VARIANT,B.ROW_ID,B.TRANSPORT_ZONE,B.DLR_CODE,B.NTW_CODE,B.PRICE_LIST,B.MRP,B.DLP,B.DEALER_MARGIN,B.BASE_MARGIN,B.MYSCORE_MARGIN,B.STOCK_MARGIN,B.PDI_CHARGES,B.TOTAL_MARGIN,SYSDATE-0.22917,SYSDATE-0.22917,B.HANDLING_CHARGES);
